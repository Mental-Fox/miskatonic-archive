const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const events={};
const ctx={console,Map,Set,document:{addEventListener:(key,fn)=>events[key]=fn},addEventListener(){},requestAnimationFrame(){},location:{hash:'#atlas/cthulhu'},fieldNotes:{},fieldReports:{},speciesProfiles:{}};
ctx.window=ctx;vm.createContext(ctx);
for(const file of ['entries.js','profiles.js','field-notes.js','books.js','bestiary-ext.js','universe.js'])vm.runInContext(fs.readFileSync(file,'utf8'),ctx,{filename:file});
ctx.records=ctx.ENTRIES;ctx.byId=new Map(ctx.records.map(r=>[r.id,r]));
ctx.escapeHTML=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
ctx.illustration=r=>'<img src="'+r.id+'">';ctx.plateImage=ctx.illustration;ctx.icon=()=>'<svg></svg>';ctx.cipherLine=x=>x;
ctx.normalize=v=>String(v??'').toLocaleLowerCase('ru').replaceAll('ё','е').trim();
let html='',mode='';
const root={open:true,classList:{contains:()=>true},querySelector:s=>s==='.tree-scroll'?{scrollTop:0}:null};ctx.$=()=>root;
ctx.openFolio=(s,m)=>{html=s;mode=m;};
vm.runInContext(fs.readFileSync('views.js','utf8'),ctx,{filename:'views.js'});
ctx.openAtlas(ctx.byId.get('cthulhu'));
assert(mode.includes('tree-mode'));assert(!mode.includes('overview-tree-mode'));
const ids=[...html.matchAll(/data-node="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length);assert(ids.length>90);
assert(html.includes('Внешние и Старшие боги'));assert(html.includes('Библиотека'));assert(html.includes('Все нити'));assert(html.includes('data-tree-path'));assert(html.includes('class="tree-card"'));
ctx.openAtlas(ctx.byId.get('azathoth'));assert.equal([...html.matchAll(/data-node="([^"]+)"/g)].length,ids.length);
const path=ctx.treePath('cthulhu','azathoth');assert(path);for(let i=1;i<path.length;i++)assert(ctx.treeLinks(path[i-1]).has(path[i]));
ctx.openAtlas(ctx.byId.get('cthulhu'),'azathoth');assert(html.includes('Убрать путь'));
events.change({target:{matches:s=>s==='[data-tree-all]',checked:true}});assert(vm.runInContext('treeState.allThreads',ctx));
console.log('PASS: restored grouped tree, full unique catalog, side card, selection, paths and all-threads toggle.');
